/** All quotes of one season, in script order. */
export function hocQuotesBySeason(season: number): HocQuote[] {
  return HOC_QUOTES.filter((q) => q.season === season);
}

/** Seasons that have at least one quote, ascending. */
export function hocQuoteSeasons(): number[] {
  return [...new Set(HOC_QUOTES.map((q) => q.season))].sort((a, b) => a - b);
}
