// Scrape per-word example sentences from the mundi-xu IELTS vocabulary site
// (https://mundi-xu.github.io/ielts) into a word -> example map the course uses.
// Internal/self-use tool.
//
//   node scripts/scrape-mundi-examples.mjs
//
// The site is a Vite SPA; its data lives in a hashed `vocabulary-*.js` chunk as
// `const e = { "01_自然地理": { words: [[{word:["atmosphere"], example:"..."}]] } }`.
// We discover the current chunk from the built assets (so it survives redeploys),
// eval the object, and write packages/core/src/data/course-examples.ts.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const SITE = 'https://mundi-xu.github.io/ielts';

function get(url) {
  return execFileSync('curl', ['-s', '--fail', '--max-time', '40', url], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
}

// 1. find the vocabulary chunk (discover its hashed name)
function findVocabChunk() {
  const index = get(`${SITE}/`);
  const entry = index.match(/assets\/(index-[A-Za-z0-9_-]+\.js)/);
  const candidates = [];
  if (entry) {
    const js = get(`${SITE}/assets/${entry[1]}`);
    for (const m of js.matchAll(/vocabulary-[A-Za-z0-9_-]+\.js/g)) candidates.push(m[0]);
    // the router chunk may reference it indirectly; also scan all chunk names
    for (const m of index.matchAll(/vocabulary-[A-Za-z0-9_-]+\.js/g)) candidates.push(m[0]);
  }
  if (candidates.length === 0) candidates.push('vocabulary-Cz9XcQe6.js'); // last-known fallback
  return [...new Set(candidates)][0];
}

const chunk = findVocabChunk();
console.error(`vocabulary chunk: ${chunk}`);
const src = get(`${SITE}/assets/${chunk}`);

// 2. extract the object literal after `const e=` (balanced braces) and eval it
const start = src.indexOf('{', src.indexOf('const e='));
let depth = 0;
let end = -1;
for (let k = start; k < src.length; k++) {
  const c = src[k];
  if (c === '{') depth++;
  else if (c === '}') {
    depth--;
    if (depth === 0) {
      end = k + 1;
      break;
    }
  }
}
if (start < 0 || end < 0) throw new Error('could not locate data object in chunk');
// eslint-disable-next-line no-eval
const data = (0, eval)('(' + src.slice(start, end) + ')');

// 3. build word -> example map
const examples = {};
let total = 0;
for (const ch of Object.keys(data)) {
  for (const group of data[ch].words) {
    for (const w of group) {
      const key = ((w.word && w.word[0]) || '').toLowerCase().trim();
      const ex = (w.example || '').trim();
      if (!key || !ex || ex === '-') continue;
      total++;
      if (!examples[key]) examples[key] = ex;
    }
  }
}
console.error(`chapters: ${Object.keys(data).length}, examples: ${Object.keys(examples).length} (from ${total} entries)`);

const out = `// AUTO-GENERATED by scripts/scrape-mundi-examples.mjs — do not edit by hand.
// Per-word example sentences from the mundi-xu IELTS vocabulary site (internal use).

/** Lowercased word -> a natural example sentence. */
export const COURSE_EXAMPLES: Record<string, string> = ${JSON.stringify(examples, null, 0)};
`;
writeFileSync(new URL('../packages/core/src/data/course-examples.ts', import.meta.url), out);
console.error('Wrote packages/core/src/data/course-examples.ts');
