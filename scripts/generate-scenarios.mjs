// Pre-generate a daily-scenario phrasebook (Hong Kong / travel oriented) into a
// typed data file for the 场景 tab. Internal/self-use tool.
//
//   NODE_USE_ENV_PROXY=1 node scripts/generate-scenarios.mjs
//   NODE_USE_ENV_PROXY=1 LIMIT=1 node scripts/generate-scenarios.mjs   # test 1
//
// Reads relay creds from apps/server/.env. Resumable via a small cache.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const CACHE = new URL('../.scenario-cache.json', import.meta.url); // gitignored
const OUT = new URL('../packages/core/src/data/scenarios.ts', import.meta.url);
const LIMIT = process.env.LIMIT ? Number(process.env.LIMIT) : Infinity;

// category id, Chinese title, Ionicons name, context hint for the model
const CATEGORIES = [
  ['immigration', '入境 · 海关', 'airplane-outline', '香港机场入境、海关、填表、行李'],
  ['transport', '交通 · 出行', 'train-outline', '香港地铁MTR、八达通、机场快线、巴士、打车'],
  ['chachaanteng', '茶餐厅 · 点餐', 'cafe-outline', '香港茶餐厅点餐（奶茶、菠萝包、餐蛋面等）、埋单'],
  ['restaurant', '餐厅 · 就餐', 'restaurant-outline', '正式餐厅订位、点餐、加单、结账、评价'],
  ['shopping', '购物 · 商场', 'bag-handle-outline', '商场购物、试穿、尺码、退换、砍价、支付'],
  ['hotel', '酒店 · 入住', 'bed-outline', '酒店办理入住退房、要求、设施、问题'],
  ['directions', '问路 · 导航', 'navigate-outline', '问路、找地点、确认方向、公共交通换乘'],
  ['convenience', '便利店 · 超市', 'cart-outline', '便利店/超市买东西、结账、找厕所、充值'],
  ['medical', '看病 · 药店', 'medkit-outline', '药店买药、描述症状、看诊所、紧急'],
  ['money', '兑换 · 支付', 'cash-outline', '货币兑换、ATM、移动支付、找零、发票'],
  ['social', '日常 · 寒暄', 'chatbubbles-outline', '打招呼、致谢致歉、闲聊、告别、请求帮助'],
  ['emergency', '紧急 · 求助', 'alert-circle-outline', '走失、报警、丢东西、身体不适、求助路人'],
];

function readEnv() {
  const env = {};
  for (const l of readFileSync(new URL('../apps/server/.env', import.meta.url), 'utf8').split('\n')) {
    const m = l.match(/^([A-Z_]+)=(.*)$/);
    if (m) env[m[1]] = m[2].trim();
  }
  return env;
}
const ENV = readEnv();
const BASE = (ENV.AI_BASE_URL || 'https://aiberm.org/v1').replace(/\/$/, '');
const KEY = ENV.AI_API_KEY;
const MODEL = ENV.AI_MODEL || 'glm-5.3';
if (!KEY) throw new Error('no AI_API_KEY in apps/server/.env');

function extractJson(s) {
  const a = s.indexOf('{');
  const b = s.lastIndexOf('}');
  if (a < 0 || b < 0) return null;
  try {
    return JSON.parse(s.slice(a, b + 1));
  } catch {
    return null;
  }
}
async function ai(messages) {
  const res = await fetch(`${BASE}/chat/completions`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${KEY}` },
    body: JSON.stringify({ model: MODEL, messages, temperature: 0.6, stream: false }),
  });
  if (!res.ok) throw new Error(`AI ${res.status}: ${(await res.text().catch(() => '')).slice(0, 200)}`);
  return (await res.json()).choices?.[0]?.message?.content ?? '';
}

const SYS =
  '你是一个面向中国游客的英语口语助手。给定一个场景，输出该场景下最实用的英语句子，' +
  '覆盖问、答、常见变体，实用、自然、口语化，适合去香港旅行/生活时直接用。' +
  '每句给：en（英文）、zh（中文意思）、tip（可选，很短的中文情境提示，说明何时用；没有就省略）。' +
  '返回严格 JSON，不要 markdown：{"sentences":[{"en":"...","zh":"...","tip":"..."}]}，共 12 句。';

let cache = {};
if (existsSync(CACHE)) {
  try {
    cache = JSON.parse(readFileSync(CACHE, 'utf8'));
  } catch {
    cache = {};
  }
}

let made = 0;
for (const [id, title, , ctx] of CATEGORIES) {
  if (made >= LIMIT) break;
  if (cache[id]) continue;
  process.stderr.write(`  gen ${id} (${title}) ...`);
  let ok = null;
  for (let attempt = 1; attempt <= 4 && !ok; attempt++) {
    try {
      const content = await ai([
        { role: 'system', content: SYS },
        { role: 'user', content: `场景：${title}（${ctx}）。生成 12 句。` },
      ]);
      const j = extractJson(content);
      if (j && Array.isArray(j.sentences) && j.sentences.length) ok = j.sentences;
      else throw new Error('bad json');
    } catch (e) {
      if (attempt === 4) throw new Error(`${id} failed: ${e.message}`);
      await new Promise((r) => setTimeout(r, 1500 * attempt));
    }
  }
  cache[id] = ok
    .filter((s) => s && s.en && s.zh)
    .map((s) => ({ en: String(s.en).trim(), zh: String(s.zh).trim(), ...(s.tip ? { tip: String(s.tip).trim() } : {}) }));
  writeFileSync(CACHE, JSON.stringify(cache));
  process.stderr.write(` ${cache[id].length} sentences\n`);
  made++;
}

if (LIMIT !== Infinity) {
  console.error(`\nLIMIT set — generated ${made}; not writing output. sample:`, JSON.stringify(cache[CATEGORIES[0][0]]?.slice(0, 2), null, 2));
  process.exit(0);
}

const missing = CATEGORIES.filter(([id]) => !cache[id]);
if (missing.length) {
  console.error(`missing ${missing.length} categories; re-run.`);
  process.exit(1);
}

const scenarios = CATEGORIES.map(([id, title, icon]) => ({ id, title, icon, sentences: cache[id] }));
const out = `// AUTO-GENERATED by scripts/generate-scenarios.mjs — do not edit by hand.
// Daily-scenario phrasebook (Hong Kong / travel oriented), for the 场景 tab.

export interface ScenarioSentence {
  en: string;
  zh: string;
  tip?: string;
}

export interface Scenario {
  id: string;
  title: string;
  icon: string;
  sentences: ScenarioSentence[];
}

export const SCENARIOS: Scenario[] = ${JSON.stringify(scenarios, null, 2)};
`;
writeFileSync(OUT, out);
console.error(`\nWrote ${scenarios.length} scenarios -> packages/core/src/data/scenarios.ts`);
