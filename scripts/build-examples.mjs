// Build packages/core/src/data/examples.ts by matching each vocab word to a
// natural example sentence from the Tatoeba English export (CC-BY 2.0 FR).
//
// Usage: node scripts/build-examples.mjs <path-to-eng_sentences.tsv>
// The TSV rows are: id <tab> lang <tab> text
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createInterface } from 'node:readline';
import { createReadStream } from 'node:fs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tsvPath = process.argv[2];
if (!tsvPath) {
  console.error('Usage: node scripts/build-examples.mjs <eng_sentences.tsv>');
  process.exit(1);
}

const words = JSON.parse(readFileSync(resolve(root, 'words.json'), 'utf8'));
const targets = new Set(words.map(([w]) => w.toLowerCase().trim()));

const IDEAL = 11; // preferred sentence length in words
// best[word] = { en, id, score }  (lower score = closer to ideal & cleaner)
const best = new Map();

const rl = createInterface({ input: createReadStream(tsvPath, 'utf8'), crlfDelay: Infinity });

let seen = 0;
rl.on('line', (line) => {
  seen++;
  const tab1 = line.indexOf('\t');
  const tab2 = line.indexOf('\t', tab1 + 1);
  if (tab1 < 0 || tab2 < 0) return;
  const id = Number(line.slice(0, tab1));
  const text = line.slice(tab2 + 1).trim();
  if (!text) return;

  // quick shape filter
  const len = text.length;
  if (len < 24 || len > 120) return;
  if (!/[.!?]$/.test(text)) return;
  if (!/^[A-Z"']/.test(text)) return;

  const tokens = text.toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g);
  if (!tokens) return;
  const wc = tokens.length;
  if (wc < 6 || wc > 18) return;

  const score = Math.abs(wc - IDEAL);
  // assign to any target word appearing exactly once
  const counts = new Map();
  for (const t of tokens) if (targets.has(t)) counts.set(t, (counts.get(t) ?? 0) + 1);
  for (const [w, c] of counts) {
    if (c !== 1) continue;
    const prev = best.get(w);
    if (!prev || score < prev.score) best.set(w, { en: text, id, score });
  }
});

rl.on('close', () => {
  const out = {};
  for (const [w, v] of best) out[w] = { en: v.en, id: v.id };
  const covered = Object.keys(out).length;

  const lines = [
    '// Auto-generated by scripts/build-examples.mjs from the Tatoeba English',
    '// export (CC-BY 2.0 FR, https://tatoeba.org). Each value is a natural',
    '// example sentence + its Tatoeba sentence id. Do not edit by hand.',
    'export interface WordExample { en: string; id: number }',
    'export const EXAMPLES: Record<string, WordExample> = {',
    ...Object.keys(out)
      .sort()
      .map((w) => `  ${JSON.stringify(w)}: { en: ${JSON.stringify(out[w].en)}, id: ${out[w].id} },`),
    '};',
    '',
  ];
  writeFileSync(resolve(root, 'packages/core/src/data/examples.ts'), lines.join('\n'));
  console.log(`Scanned ${seen} sentences; matched ${covered}/${targets.size} words -> packages/core/src/data/examples.ts`);
});
